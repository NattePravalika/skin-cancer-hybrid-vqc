    total_loss = 0
    for xb, yb in tqdm(vqc_loader, desc=f"VQC Epoch {epoch+1}/{EPOCHS_VQC}", leave=False):
        vqc_optimizer.zero_grad()
        loss = loss_fn(vqc(xb), yb)
        loss.backward(); vqc_optimizer.step()
        total_loss += loss.item()
