def extract_features(loader, desc="Extracting"):
    feats, labels = [], []
    with torch.no_grad():
        for x, y in tqdm(loader, desc=desc):
            feats.append(backbone(x.to(DEVICE)).cpu().numpy())
            labels.append(y.numpy())
    return np.vstack(feats), np.concatenate(labels)

