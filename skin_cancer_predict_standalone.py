    vqc.eval()
    with torch.no_grad():
        val_acc = accuracy_score(val_y, torch.argmax(vqc(X_val_vqc), dim=1).cpu().numpy())

    vqc_history['loss'].append(total_loss)
    vqc_history['val_acc'].append(val_acc)

